SLOT: dict[str, tuple[int, int]] = {
    name: ((i % 16) * 16, (i // 16) * 16) for i, name in enumerate(ART)
}


def load_sprites() -> None:
    img = pyxel.images[0]
    for name, rows in ART.items():
        u, v = SLOT[name]
        doubled = []
        for row in rows:
            line = "".join(c * 2 for c in row.replace(".", "0"))
            doubled += [line, line]
        img.set(u, v, doubled)
